// Checks on the REAL site after a release (iPhone 13 Pro and SE): 4d6 thrown on screen, a level 5 start, HP, a 3D throw, tabs.
// Run: node scripts/live.cjs  (nothing is stored on a server: characters stay in the test browser)
const { chromium, devices } = require('playwright')
const URL = process.env.SITE || 'https://guyyyy15-web.github.io/party-sheets/'
let fails = 0
const ok = (c, m) => { console.log(`${c ? 'ok ' : 'FAIL'} ${m}`); if (!c) fails++ }
;(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  for (const [devName, dev] of [['iPhone 13 Pro', devices['iPhone 13 Pro']], ['iPhone SE', devices['iPhone SE']]]) {
    const ctx = await b.newContext({ ...dev })
    // the real site, but its test characters must not land in the real database: saving points at a closed port
    await ctx.addInitScript(() => (localStorage.setItem('ps.api', JSON.stringify('http://127.0.0.1:9')), localStorage.setItem('ps.seenLanding', 'true')))
    const p = await ctx.newPage()
    const errs = []
    p.on('pageerror', (e) => errs.push(e.message))
    const t0 = Date.now()
    await p.goto(URL)
    await p.waitForSelector('text=No heroes yet')
    ok(true, `${devName}: home in ${Date.now() - t0} ms`)
    await p.click('text=+ New character')
    await p.fill('input[placeholder="e.g. Katsebushi"]', 'Tester')
    await p.click('button[aria-label="Level up"]'); await p.click('button[aria-label="Level up"]'); await p.click('button[aria-label="Level up"]'); await p.click('button[aria-label="Level up"]')
    await p.click('.wiz-foot button')
    await p.click('.class-card:has-text("Fighter")'); await p.click('.wiz-foot button')
    await p.click('.card:has-text("Goliath")'); await p.click('.panel .card:has-text("Stone")'); await p.click('.wiz-foot button')
    await p.click('.card:has-text("Sage")'); await p.click('button:has-text("+1 to all three")')
    ok(!(await p.isEnabled('.wiz-foot button')), `${devName}: Sage asks for its Magic Initiate spells (the list is fixed: Wizard)`)
    for (const n of ['Intelligence', 'Fire Bolt', 'Light', 'Magic Missile']) await p.click(`.panel .card:has(.opt-name:text-is("${n}"))`)
    ok(await p.isEnabled('.wiz-foot button'), `${devName}: with the spells picked, the background is done`)
    await p.click('.wiz-foot button')
    // 4d6 thrown on screen, six times
    await p.click('button:has-text("Roll 4d6")')
    const t1 = Date.now()
    await p.click('button:has-text("Roll 4d6 six times")')
    await p.waitForFunction(() => document.querySelectorAll('.roll-chip').length === 6 && !document.querySelector('button[disabled]:is(:not(.die-minus))')?.textContent.includes('Rolling'), null, { timeout: 120000 })
    const vals = await p.$$eval('.roll-chip b', (e) => e.map((x) => Number(x.textContent)))
    ok(vals.length === 6 && vals.every((v) => v >= 3 && v <= 18), `${devName}: 4d6 x6 thrown on screen in ${((Date.now() - t1) / 1000).toFixed(0)} s: ${vals.join(', ')}`)
    const overlay = await p.evaluate(() => getComputedStyle(document.querySelector('.dice3d') || document.body).display)
    ok(overlay === 'none' || overlay === 'block', `${devName}: dice overlay state ${overlay}`)
    await p.click('button:has-text("Suggest for")')
    await p.click('.wiz-foot button')
    // level 5 fighter: skills, style, mastery x4 (level 4), ASI at 4, subclass at 3
    for (const t of ['Perception', 'Survival', 'Defense', 'Greatsword', 'Longsword', 'Longbow', 'Javelin', 'Champion']) await p.click(`.panel.choice .card:has-text("${t}")`)
    await p.click('.panel.choice .abil-grid .chip >> nth=0')
    ok(await p.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `${devName}: the choices page fits the width (icons, long names)`)
    ok(await p.isEnabled('.wiz-foot button'), `${devName}: level 5 start: subclass, 4 masteries and the level 4 ASI are asked for`)
    await p.click('.wiz-foot button'); await p.click('.card.opt >> nth=0'); await p.click('.wiz-foot button')
    await p.click('button:has-text("Start playing")')
    await p.waitForSelector('.vitals')
    ok(/2 per Attack action/.test(await p.textContent('.turn')), `${devName}: level 5 fighter attacks twice`)
    ok(/crit on 19/.test(await p.textContent('.turn')), `${devName}: Champion crits on 19`)
    // HP: damage, temp, heal
    const hpText = async () => (await p.textContent('.hp b')).replace(/\s/g, '')
    const full = await hpText()
    await p.click('.hp'); await p.fill('input[aria-label="Amount"]', '7'); await p.click('.sheet button:text-is("Damage")')
    const max = Number(full.split('/')[1])
    ok((await hpText()) === `${max - 7}/${max}`, `${devName}: 7 damage (${full} → ${await hpText()})`)
    await p.click('.hp'); await p.fill('input[aria-label="Amount"]', '5'); await p.click('.sheet button:text-is("Temp HP")')
    await p.click('.hp'); await p.fill('input[aria-label="Amount"]', '6'); await p.click('.sheet button:text-is("Damage")')
    ok((await hpText()) === `${max - 8}/${max}`, `${devName}: temp HP soaks damage first`)
    await p.click('button:has-text("Long rest")').catch(() => {})
    // a 3D throw from the tray on the sheet
    await p.click('.fab')
    await p.click('button[aria-label="Add a d8"]')
    const t2 = Date.now()
    await p.click('button:has-text("Throw d20 + d8")')
    await p.waitForFunction(() => /Tap to close/.test(document.querySelector('.dice3d')?.textContent || ''), null, { timeout: 30000 })
    const txt = await p.evaluate(() => document.querySelector('.dice3d').innerText.replace(/\s+/g, ' '))
    const m = /(\d+) d20\[(\d+)\] d8\[(\d+)\]/.exec(txt)
    ok(m && Number(m[1]) === Number(m[2]) + Number(m[3]), `${devName}: 3D throw settles in ${((Date.now() - t2) / 1000).toFixed(1)} s and adds up (${txt.trim()})`)
    await p.click('.dice3d')
    await p.screenshot({ path: `screenshots/live-${devName.replace(' ', '')}.png` })
    for (const tab of ['Checks', 'Features', 'Gear', 'Notes', 'My Turn']) {
      await p.click(`[role=tab]:has-text("${tab}")`)
      const w = await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
      if (!w) ok(false, `${devName}: ${tab} scrolls sideways`)
    }
    ok(true, `${devName}: every tab fits the width`)
    ok(!errs.length, `${devName}: no page errors ${errs.join(' | ')}`)
    await ctx.close()
  }
  await b.close()
  console.log(fails ? `\n${fails} failed` : '\nall good')
})()
